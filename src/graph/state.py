"""
GraphState 定义

LangGraph 全局状态，所有 Agent 的"接口合约"。
"""

from typing import TypedDict, List, Optional


class GraphState(TypedDict):
    """
    LangGraph 全局状态定义

    所有 Node 函数通过此 State 进行通信。
    每个 Node 返回 dict，仅更新需要修改的字段。
    """

    # ============================================================
    # 用户标识
    # ============================================================
    user_id: str                              # 用户ID（记忆隔离）
    session_id: str                           # 会话ID（对话隔离）

    # ============================================================
    # 剧情控制
    # ============================================================
    total_episodes: int                       # 预期总集数
    current_episode: int                      # 当前集数
    style: str                                # 风格设定

    # ============================================================
    # 大纲与词汇
    # ============================================================
    outline: List[str]                        # 各集大纲
    target_words: List[str]                   # 当前集目标词汇
    used_words: List[str]                     # 已使用的目标词汇

    # ============================================================
    # 生成内容
    # ============================================================
    draft_text: str                           # 当前草稿
    final_text: str                           # 最终文本（可能带标注）

    # ============================================================
    # 审查结果
    # ============================================================
    is_valid: bool                            # 是否通过审查
    feedback_list: List[str]                  # 审查反馈
    out_of_scope_words: List[str]             # 超纲词列表
    out_of_scope_ratio: float                 # 超纲词占比

    # ============================================================
    # 流程控制
    # ============================================================
    retry_count: int                          # 当前重试次数
    adjust_count: int                         # Planner 调整次数
    fallback_mode: bool                       # 是否触发兜底机制

    # ============================================================
    # 记忆管理
    # ============================================================
    story_bible: dict                         # 故事圣经（核心设定）
    previous_summary: str                     # 前情提要


# ============================================================
# 常量定义
# ============================================================

MAX_RETRIES: int = 5      # 单轮最大重试次数
MAX_ADJUSTS: int = 2      # Planner 最大调整次数
MAX_RATIO: float = 0.05   # 兜底允许的高级词占比
